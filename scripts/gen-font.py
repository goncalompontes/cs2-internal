#!/usr/bin/env python3
"""Embed a font file as a C++ byte array for the ESP overlay.

Usage: gen-font.py INPUT.ttf OUTPUT.cpp

Writes a translation unit defining `cs2::render::k_esp_font_ttf` /
`k_esp_font_ttf_size` (declared in `cs2/render/esp_font.hpp`).
"""
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen-font.py INPUT.ttf OUTPUT.cpp", file=sys.stderr)
        return 2
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, "rb") as handle:
        data = handle.read()
    with open(dst, "w", encoding="utf-8") as out:
        out.write(f"// Generated by scripts/gen-font.py from {src} -- do not edit.\n")
        out.write('#include "cs2/render/esp_font.hpp"\n\n')
        out.write("namespace cs2::render {\n\n")
        out.write("extern const unsigned char k_esp_font_ttf[] = {\n")
        for i in range(0, len(data), 16):
            chunk = data[i : i + 16]
            out.write("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
        out.write("};\n\n")
        out.write(f"extern const std::size_t k_esp_font_ttf_size = {len(data)};\n\n")
        out.write("}  // namespace cs2::render\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
