#!/usr/bin/env python3
"""Render the settings name table from the wire format's `Settings` struct.

The control channel addresses a feature setting by its flat wire field name
(`esp_box`, `movement_thirdperson_distance`, ...), and the byte offset of a
field is a property of the packed layout -- hand-maintaining 87 entries is
exactly the kind of table that drifts. This generator parses
`overlay/include/cs2/overlay/wire.hpp` and emits
`overlay/include/cs2/overlay/settings_table.hpp`.

The struct is `#pragma pack(push, 1)`, so the layout has no padding: a field's
offset is the sum of the sizes before it.

Usage: gen-settings-table.py [--check] [WIRE_HPP] [OUT_HPP] [STAMP]

  WIRE_HPP  the wire header to parse (default: <repo>/overlay/include/cs2/overlay/wire.hpp)
  OUT_HPP   the header to write     (default: <repo>/overlay/include/cs2/overlay/settings_table.hpp)
  STAMP     optional file to touch on success (used by the Meson target)

  --check   do not write; compare the generated text with OUT_HPP and fail
            (exit 1) when they differ. Used by the `settings-table` test.
            The comparison is on the *text*, so it does not care whether the
            file uses LF or CRLF.

A parse failure is **fatal**: the script prints what it could not parse and
exits non-zero. An empty table would silently make every settings name
unknown, which is worse than no table at all.

A rewrite keeps the line ending the file already has, so regenerating it does
not turn a CRLF checkout into a "modified" file.
"""
import re
import sys
from pathlib import Path

# The field declarations the settings block uses. Anything else is a parse
# failure (the generator refuses to guess).
FIELD_RE = re.compile(
    r"^\s*(?P<type>uint8_t|uint32_t|float|char)\s+(?P<name>[A-Za-z_]\w*)"
    r"(?:\s*\[\s*(?P<count>\d+)\s*\])?\s*;\s*(?://.*)?$"
)
# A `// --- group ---` heading: the section a field sits in.
SECTION_RE = re.compile(r"^\s*//\s*-{3,}\s*(?P<name>.*?)\s*-{3,}\s*$")
COMMENT_RE = re.compile(r"^\s*//")
BLANK_RE = re.compile(r"^\s*$")

# The storage class of each supported declaration: (size, count, type).
#   uint8_t        a one-byte field (a toggle, a mode, a small number)
#   uint32_t       a four-byte unsigned counter
#   float          a four-byte number
#   uint8_t[4]     a colour (RGBA)
#   char[N]        a NUL-terminated text
LAYOUT = {
    "uint8_t": (1, 1, "flag"),
    "uint32_t": (4, 1, "unsigned_number"),
    "float": (4, 1, "number"),
}

# The colour's channel count: a `uint8_t[4]` is an RGBA colour.
COLOUR_CHANNELS = 4

HEADER_TEMPLATE = """#pragma once

// GENERATED by scripts/gen-settings-table.py - do not edit.
//
// The name -> offset table for `wire::Settings` (ADR-0021). The control
// channel's `settings` command addresses a setting by its flat field name, and
// the offsets depend on the packed layout, so they are generated rather than
// hand-maintained.
//
// The file is **checked in** and both builds **verify** it: the Meson targets
// run `scripts/gen-settings-table.py --check` and fail when the table is out
// of date, so a stale table can never reach a build (a stale offset would
// write a neighbouring field's bytes -- silent corruption, no error).
//
// Regenerate with `python scripts/gen-settings-table.py` and commit the result.

#include <array>
#include <cstddef>
#include <cstdint>
#include <string_view>

namespace cs2::overlay::wire {{

// How a settings field is read and written: a one-byte field, a number, an
// unsigned counter, a colour or a text.
enum class SettingType : std::uint8_t {{
  flag = 0,             // a one-byte field (a toggle, a mode, a small number)
  number = 1,           // a float
  unsigned_number = 2,  // a uint32_t (a monotonic counter)
  colour = 3,           // four bytes (RGBA)
  text = 4,             // a NUL-terminated char array
  count = 5,            // the number of kinds
}};

// One field of `Settings`: its flat name, the section it sits in, its kind and
// where it lives in the packed struct.
struct SettingInfo {{
  std::string_view name;     // the flat field name, e.g. "esp_color_enemy"
  std::string_view section;  // the "--- group ---" heading it sits under
  SettingType type;
  std::size_t offset;  // byte offset into Settings
  std::size_t size;    // 1 (flag) | 4 (number) | N (text)
  std::size_t count;   // element count for colour/text, else 1
}};

// Every field of `Settings`, in declaration order.
inline constexpr std::array<SettingInfo, {count}> SETTING_TABLE = {{{{
{entries}
}}}};

// The field named `name`, or null when the struct has no such field.
[[nodiscard]] inline auto find_setting(std::string_view name) noexcept -> const SettingInfo* {{
  for (const SettingInfo& info : SETTING_TABLE) {{
    if (info.name == name) {{
      return &info;
    }}
  }}
  return nullptr;
}}

}}  // namespace cs2::overlay::wire
"""


class ParseError(Exception):
    """A parse failure: the generator must not emit a table it cannot trust."""


def parse_settings(text: str) -> list[tuple[str, str, str, int, int, int]]:
    """Parse the `Settings` struct into (name, section, type, offset, size, count)."""
    lines = text.splitlines()
    start = None
    for index, line in enumerate(lines):
        if re.match(r"^\s*struct\s+Settings\s*\{", line):
            start = index
            break
    if start is None:
        raise ParseError("no `struct Settings` found")

    fields: list[tuple[str, str, str, int, int, int]] = []
    section = ""
    offset = 0
    for index in range(start + 1, len(lines)):
        line = lines[index]
        number = index + 1
        if re.match(r"^\s*}\s*;", line):  # the end of the struct
            break
        if BLANK_RE.match(line) or COMMENT_RE.match(line):
            heading = SECTION_RE.match(line)
            if heading is not None:
                section = heading.group("name").strip()
            continue
        match = FIELD_RE.match(line)
        if match is None:
            raise ParseError(f"line {number}: cannot parse a field declaration: {line.strip()!r}")
        kind = match.group("type")
        name = match.group("name")
        count_text = match.group("count")
        if kind == "char":
            if count_text is None:
                raise ParseError(f"line {number}: {name!r} is a `char` without a length")
            length = int(count_text)
            if length <= 0:
                raise ParseError(f"line {number}: {name!r} has a length of {length}")
            fields.append((name, section, "text", offset, length, length))
            offset += length
            continue
        if count_text is not None:
            length = int(count_text)
            if kind == "uint8_t" and length == COLOUR_CHANNELS:
                fields.append((name, section, "colour", offset, COLOUR_CHANNELS, COLOUR_CHANNELS))
                offset += COLOUR_CHANNELS
                continue
            raise ParseError(
                f"line {number}: unsupported declaration {kind}[{length}] for {name!r} "
                f"(only uint8_t[{COLOUR_CHANNELS}] is known)"
            )
        size, count, type_name = LAYOUT[kind]
        fields.append((name, section, type_name, offset, size, count))
        offset += size
    else:
        raise ParseError("the end of `struct Settings` was not found")

    if not fields:
        raise ParseError("`struct Settings` has no fields")
    names = [field[0] for field in fields]
    duplicates = {name for name in names if names.count(name) > 1}
    if duplicates:
        raise ParseError(f"duplicate field names: {sorted(duplicates)}")
    return fields


def render(fields: list[tuple[str, str, str, int, int, int]]) -> str:
    """Render the generated header."""
    entries = "\n".join(
        '    {{"{name}", "{section}", SettingType::{type}, {offset}, {size}, {count}}},'.format(
            name=name,
            section=section,
            type=type_name,
            offset=offset,
            size=size,
            count=count,
        )
        for name, section, type_name, offset, size, count in fields
    )
    return HEADER_TEMPLATE.format(count=len(fields), entries=entries)


def line_ending(path: Path) -> str:
    """The line ending the file already uses (``"\r\n"`` or ``"\n"``).

    A checkout on Windows has CRLF, and a regeneration that wrote LF would
    leave the file showing as modified in every working tree (the content is
    the same, but the bytes are not).  The rewrite therefore keeps the
    ending the file already has; the *check* compares the text, so it is
    indifferent to the ending either way.
    """
    try:
        data = path.read_bytes()
    except OSError:
        return "\n"
    return "\r\n" if b"\r\n" in data else "\n"


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parent.parent
    args = list(argv)
    check = False
    if args and args[0] == "--check":
        check = True
        args = args[1:]

    wire = Path(args[0]) if len(args) > 0 else root / "overlay" / "include" / "cs2" / "overlay" / "wire.hpp"
    out = Path(args[1]) if len(args) > 1 else root / "overlay" / "include" / "cs2" / "overlay" / "settings_table.hpp"
    stamp = Path(args[2]) if len(args) > 2 and args[2] else None

    try:
        source = wire.read_text(encoding="utf-8")
    except OSError as error:
        print(f"gen-settings-table: cannot read {wire}: {error}", file=sys.stderr)
        return 2
    try:
        fields = parse_settings(source)
    except ParseError as error:
        print(f"gen-settings-table: {wire}: {error}", file=sys.stderr)
        return 2

    generated = render(fields)
    if check:
        try:
            current = out.read_text(encoding="utf-8")
        except OSError as error:
            print(f"gen-settings-table: cannot read {out}: {error}", file=sys.stderr)
            return 1
        if current != generated:
            print(
                f"gen-settings-table: {out} is out of date "
                f"(run `python scripts/gen-settings-table.py`)",
                file=sys.stderr,
            )
            return 1
        if stamp:
            stamp.parent.mkdir(parents=True, exist_ok=True)
            stamp.touch()
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    # Only rewrite the file when the content changed: the Meson target runs on
    # every build, and a stable mtime keeps the dependents from rebuilding.
    try:
        current = out.read_text(encoding="utf-8")
    except OSError:
        current = None
    if current != generated:
        out.write_text(generated, encoding="utf-8", newline=line_ending(out))
    if stamp:
        stamp.parent.mkdir(parents=True, exist_ok=True)
        stamp.touch()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
